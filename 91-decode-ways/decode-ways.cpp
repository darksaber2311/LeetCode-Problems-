class Solution {
public:
    int numDecodings(string s) {
        // cant be grouped
        // 01 27 30

        //12 = 1,2 and 12
        //123 = 1,2,3 and 12,3 and 1,23 

        // 127 = 1,2,7 and  12,7
        // 131 = 1,3,1 and 13,1

        // 1311 = 1,3,1,1 and 13,11 and 1,3,11  

        // 287 = 2,8,7

        // 122 = 12,2 and 1,2,2 and 1,22  dp[2] = dp[1] + dp[0] = 3
        // 1221 = 1,2,2,1 and 1,22,1 and 12,21 and 1,2,21 and 12,2,1  dp[3] = dp[1] + dp[2] = 2 + 3

        // 1220 = 1,2,20 and 12,20

        // 120 = 1,20
        // 1201 = 1,20,1

        // 1 = 1
        // 11 = 1,1 and 11
        // 111 = 1,1,1 and 1,11 and 11,1
        // 1110 = 1,1,10 and 11,10
        // 11106 = 1,1,10,6 and 11,10,6
        // 111065 = 1,1,10,6,5 and 11,10,6,5
        //111025 = 1,1,10,2,5 and 11,10,2,5 and 11,10,25 and 1,1,10,25

        // 1220 = 1,2,20 and 12,20
        //12201 = 1,2,20,1 and 12,20,1
        // 122010 = 1,2,20,10 and 12,20,10
        //1220102 = 

        int n = s.size();
        vector<int> dp(n);
        if(s[0] == '0')return 0;
        if(n == 1) return 1;

        dp[0] = 1;
        dp[1] = (s[0] > '2' || s[1] == '0' ||(s[0] == '2' && s[1]>'6') ) ? 1:2;
        if(s[0] >'2' && s[1] == '0')return 0; 
        for(int i = 2;i<n;i++)
        {
            if(s[i] == '0')
            {
                if(s[i-1]== '0' || s[i-1]>'2')return 0;
                else dp[i] = dp[i-2];
            }
            else if(s[i-1]>'2' || s[i-1] == '0' || (s[i-1] =='2' && s[i]>'6'))dp[i] = dp[i-1];
            else dp[i] = dp[i-1] + dp[i-2];

        }
        return dp[n-1];
    }
};